import { z, type ZodType } from "zod";
import type { ResponseConfig, RouteConfig } from "@asteasolutions/zod-to-openapi";
import { ERROR_STATUS, type ErrorCode } from "../errors/codes";
import { operations, registry, type OperationDef } from "./registry";

const ERROR_CODES = Object.keys(ERROR_STATUS) as [ErrorCode, ...ErrorCode[]];

const requestMeta = z.object({
  requestId: z
    .string()
    .describe("Echo of the X-Request-Id response header; quote it in bug reports"),
});

const paginationSchema = z.object({
  page: z.number().int(),
  pageSize: z.number().int(),
  totalItems: z.number().int(),
  totalPages: z.number().int(),
});

/** `{ success: true, data, meta: { requestId } }`, registered as a named component. */
export function SuccessEnvelope(name: string, data: ZodType) {
  return registry.register(name, z.object({ success: z.literal(true), data, meta: requestMeta }));
}

/** Like `SuccessEnvelope` for list endpoints: `data` is an array and `meta.pagination` is present. */
export function PaginatedEnvelope(name: string, item: ZodType) {
  return registry.register(
    name,
    z.object({
      success: z.literal(true),
      data: z.array(item),
      meta: requestMeta.extend({ pagination: paginationSchema }),
    }),
  );
}

export const ErrorEnvelope = registry.register(
  "ErrorEnvelope",
  z.object({
    success: z.literal(false),
    error: z.object({
      code: z
        .enum(ERROR_CODES)
        .describe("Machine-readable error code; branch on this, not on message"),
      message: z.string(),
      details: z
        .array(z.object({ path: z.string(), message: z.string() }))
        .optional()
        .describe("Present on VALIDATION_ERROR: one entry per invalid field"),
    }),
    meta: requestMeta,
  }),
);

registry.registerComponent("securitySchemes", "bearerAuth", {
  type: "http",
  scheme: "bearer",
  bearerFormat: "JWT",
  description: "Access token from /auth/login, /auth/register or /auth/refresh.",
});

registry.registerComponent("headers", "XRequestId", {
  description: "Request correlation id (echo of the request header, or generated by the server).",
  schema: { type: "string" },
});

registry.registerComponent("headers", "RetryAfter", {
  description: "Seconds to wait before retrying.",
  schema: { type: "integer", minimum: 1 },
});

export const XClientId = registry.registerParameter(
  "XClientId",
  z.string().openapi({
    param: { name: "X-Client-Id", in: "header", required: false },
    description:
      "Tenant slug. Required in shared-mode deployments for operations without a bearer token " +
      "(the token carries the tenant otherwise; when both are sent they must match). " +
      "Optional in dedicated deployments, where the tenant is fixed. Android apps should always send it.",
    example: "acme",
  }),
);

export const XRequestId = registry.registerParameter(
  "XRequestIdParam",
  z.string().openapi({
    param: { name: "X-Request-Id", in: "header", required: false },
    description:
      "Optional correlation id (8-64 characters from A-Za-z0-9._-); generated when absent or invalid.",
  }),
);

const STATUS_TEXT: Record<number, string> = {
  400: "Bad request",
  401: "Unauthenticated",
  403: "Forbidden",
  404: "Not found",
  409: "Conflict",
  413: "Payload too large",
  429: "Too many requests",
  500: "Internal error",
};

function codesFor(status: number): string[] {
  return Object.entries(ERROR_STATUS)
    .filter(([, s]) => s === status)
    .map(([code]) => code);
}

/** Error statuses an operation can return, derived from its route config plus `extraErrors`. */
export function errorStatuses(op: OperationDef): number[] {
  const s = new Set<number>([500, ...(op.extraErrors ?? [])]);
  if (op.body || op.query || op.params || op.tenant === "required") s.add(400); // incl. INVALID_CLIENT
  if (op.auth === "required") s.add(401);
  if (op.tenant === "required") s.add(403);
  if (op.params) s.add(404);
  if (op.body) s.add(413);
  if (op.rateLimit && op.rateLimit.length > 0) s.add(429);
  return [...s].sort((a, b) => a - b);
}

function errorResponse(op: OperationDef, status: number): ResponseConfig {
  const requestId = { $ref: "#/components/headers/XRequestId" };
  let description = `${STATUS_TEXT[status] ?? "Error"}. Possible codes: ${codesFor(status).join(", ")}.`;
  const headers: NonNullable<ResponseConfig["headers"]> = { "X-Request-Id": requestId };
  if (status === 429) {
    headers["Retry-After"] = { $ref: "#/components/headers/RetryAfter" };
    const limits = (op.rateLimit ?? [])
      .map((r) => `${r.name}: ${r.limit} per ${r.windowSeconds}s`)
      .join("; ");
    description += ` Limits (per instance): ${limits}.`;
  }
  return {
    description,
    headers,
    content: { "application/json": { schema: ErrorEnvelope } },
  };
}

/** Registers an operation and derives its parameters, security and error responses. */
export function registerOperation(op: OperationDef): void {
  operations.push(op);
  const responses: RouteConfig["responses"] = {};
  for (const s of op.success) {
    responses[s.status] = {
      description: s.description,
      headers: {
        "X-Request-Id": { $ref: "#/components/headers/XRequestId" },
        ...s.headers,
      },
      content: { "application/json": { schema: s.schema } },
    };
  }
  for (const status of errorStatuses(op)) responses[status] = errorResponse(op, status);

  registry.registerPath({
    method: op.method,
    path: op.path,
    operationId: op.operationId,
    tags: [op.tag],
    summary: op.summary,
    ...(op.description ? { description: op.description } : {}),
    // `security: []` marks the operation as public, overriding any default.
    security: op.auth === "required" ? [{ bearerAuth: [] }] : [],
    request: {
      ...(op.params ? { params: op.params as z.ZodObject } : {}),
      ...(op.query ? { query: op.query as z.ZodObject } : {}),
      headers: [...(op.tenant === "required" ? [XClientId] : []), XRequestId],
      ...(op.body
        ? { body: { required: true, content: { "application/json": { schema: op.body } } } }
        : {}),
    },
    responses,
  });
}
